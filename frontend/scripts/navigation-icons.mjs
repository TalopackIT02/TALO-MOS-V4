// Navigation icon library manifest. The SVG files live in public/assets/icons/navigation/ (added by the owner through the
// development process); this script lists their names into src/components/icons/navigationIconNames.ts so the shell can
// accept only icon keys that exist (no path, no arbitrary SVG). Usage: node scripts/navigation-icons.mjs [--check]
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'public/assets/icons/navigation');
const out = resolve(root, 'src/components/icons/navigationIconNames.ts');
const KEY = /^[a-z0-9]+(-[a-z0-9]+)*$/;

const names = existsSync(dir)
  ? readdirSync(dir).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).filter((n) => KEY.test(n)).sort()
  : [];
const body = `// GENERATED by scripts/navigation-icons.mjs from public/assets/icons/navigation/ — do not edit by hand.\n`
  + `export const NAVIGATION_ICON_NAMES: readonly string[] = ${JSON.stringify(names)};\n`;

const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
if (process.argv.includes('--check')) {
  if (current !== body) {
    console.error('[icons] navigationIconNames.ts is out of date — run: node scripts/navigation-icons.mjs');
    process.exit(1);
  }
  console.log(`[icons] manifest up to date (${names.length} icons)`);
} else if (current !== body) {
  writeFileSync(out, body);
  console.log(`[icons] manifest written (${names.length} icons)`);
} else {
  console.log(`[icons] manifest unchanged (${names.length} icons)`);
}
